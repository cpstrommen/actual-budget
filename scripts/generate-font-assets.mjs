#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const source = path.join(root, 'assets/fonts/geologica');
const font = await readFile(path.join(source, 'Geologica.ttf'));
const license = (
  await readFile(path.join(source, 'OFL.txt'), 'utf8')
).replaceAll('\r\n', '\n');
if (license.includes('*/')) {
  throw new Error('Font license cannot be embedded in a CSS comment');
}
const css =
  '/* ' +
  license +
  ' */\n@font-face{font-family:Geologica;font-style:normal;font-weight:100 900;font-display:swap;src:url(data:font/ttf;base64,' +
  font.toString('base64') +
  ') format("truetype")}';
await writeFile(
  path.join(root, 'packages/loot-core/src/shared/geologica-font.ts'),
  '// Generated by scripts/generate-font-assets.mjs from assets/fonts/geologica.\n// Includes the SIL Open Font License; do not edit this generated file.\n// prettier-ignore\nexport const GEOLOGICA_FONT_CSS = ' +
    JSON.stringify(css) +
    ';\n',
);
process.stdout.write(
  'Generated self-contained Geologica CSS for offline report exports.\n',
);
